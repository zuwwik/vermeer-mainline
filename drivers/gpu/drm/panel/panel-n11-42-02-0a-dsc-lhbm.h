static const u16 n11_lhbm_white_coefficients[] = {
	10561, 10550, 10512, 10473, 10440, 10410, 10390,
	10366, 10343, 10323, 10300, 10280, 10250, 10209,
};

struct n11_lhbm_parameters {
	u16 alpha;
	u16 dbv;
	u8 rgb[6];
};

static inline int n11_lhbm_parameters(unsigned int brightness, const u8 *calibration,
				      struct n11_lhbm_parameters *parameters)
{
	static const u16 upper[] = {
		2047, 2293, 2440, 2637, 2858, 2957, 3055,
		3154, 3275, 3375, 3476, 3590, 3791,
	};
	unsigned int index = 0;

	if (brightness > 4095)
		return -EINVAL;
	/* Above the last calibrated interval, keep its coefficient. */
	while (index < ARRAY_SIZE(upper) && brightness > upper[index])
		index++;
	parameters->alpha = 0x1000 | (brightness > 327 ? 0xfff :
				    n11_lhbm_alpha[brightness]);
	parameters->dbv = brightness > 327 ? brightness * 4 : 0x051c;
	for (unsigned int i = 0; i < 3; i++) {
		unsigned int value = get_unaligned_be16(calibration + 2 * i);

		if (!value || value > 0xfff)
			return -ENODATA;
		value = value * n11_lhbm_white_coefficients[index] / 10000;
		if (value > 0xfff)
			return -ERANGE;
		put_unaligned_be16(value, parameters->rgb + 2 * i);
	}

	return 0;
}

